import sys
import os
import json

# Add backend directory to sys.path
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from fastapi.testclient import TestClient
from app.main import app

client = TestClient(app)

def test_health():
    print("Testing GET /api/v1/health...")
    response = client.get("/api/v1/health")
    assert response.status_code == 200, f"Expected 200, got {response.status_code}"
    data = response.json()
    print("Health response:", data)
    assert data["status"] == "healthy"
    print("Health check passed!\n")

def test_sample_fields():
    print("Testing GET /api/v1/sample-fields...")
    response = client.get("/api/v1/sample-fields")
    assert response.status_code == 200
    data = response.json()
    assert len(data.get("fields", [])) > 0
    print(f"Sample fields count: {len(data['fields'])}")
    print("Sample fields passed!\n")

def test_analyze_terrain_phase2():
    print("Testing POST /api/v1/analyze-terrain with Phase II full stack (A* routing, ML risk, AI advisory)...")
    payload = {
        "coordinates": [
            [75.9238, 26.9845],
            [75.9272, 26.9848],
            [75.9278, 26.9818],
            [75.9242, 26.9815],
            [75.9238, 26.9845]
        ],
        "grid_resolution": 15,
        "soil_type": "clay",
        "crop_type": "Wheat",
        "rainfall_mm": 70.0,
        "include_phase2": True
    }
    response = client.post("/api/v1/analyze-terrain", json=payload)
    assert response.status_code == 200, f"Got error {response.status_code}: {response.text}"
    data = response.json()

    print("Status:", data.get("status"))
    print("Bounding Box:", data.get("bounding_box"))
    print(f"Elevation grid shape: {len(data['elevation_grid'])}x{len(data['elevation_grid'][0])}")
    print(f"Waterlogging zones count: {len(data['waterlogging_zones'])}")

    # Phase II assertions
    drainage_routes = data.get("drainage_routes")
    print(f"\n[Phase II] Drainage routes generated: {len(drainage_routes or [])}")
    if drainage_routes:
        r = drainage_routes[0]
        print(f"  Route 1: Length={r['length_meters']}m, Drop={r['elevation_drop_meters']}m, Slope={r['slope_percent']}%, Volume={r['excavation_volume_m3']}m³, Cost=₹{r['estimated_cost_inr']}")

    risk = data.get("risk_simulation")
    print(f"\n[Phase II] Soil & Rainfall ML Simulation:")
    if risk:
        print(f"  Soil: {risk['soil_name']}, Runoff Vol={risk['runoff_volume_m3']}m³ ({risk['runoff_volume_megaliters']} ML), Ponding Depth={risk['estimated_ponding_depth_cm']}cm, Risk={risk['crop_loss_risk_percent']}% ({risk['risk_level']})")

    advisory = data.get("ai_advisory")
    print(f"\n[Phase II] AI Advisory:")
    if advisory:
        print(f"  Headline: {advisory['headline']}")
        print(f"  Generated By: {advisory['generated_by']}")
        print(f"  Drainage Tip: {advisory['drainage_recommendations'][0]}")

    cut_fill = data.get("cut_fill_analysis")
    print(f"\n[Precision Land Leveling] Cut & Fill Optimization:")
    if cut_fill:
        print(f"  Total Cut: {cut_fill['total_cut_m3']} m³, Total Fill: {cut_fill['total_fill_m3']} m³")
        print(f"  Cut:Fill Ratio: {cut_fill['cut_fill_ratio']}, Slope: {cut_fill['design_slope_percent']}%, Heading: {cut_fill['design_heading_degrees']}° ({cut_fill['heading_compass']})")
        print(f"  Leveling Cost: ₹{cut_fill['estimated_leveling_cost_inr']}")

    assert data["status"] == "success"
    assert drainage_routes is not None
    assert risk is not None
    assert advisory is not None
    assert cut_fill is not None
    print("\nALL PHASE I & PHASE II BACKEND TESTS PASSED SUCCESSFULLY!")

if __name__ == "__main__":
    test_health()
    test_sample_fields()
    test_analyze_terrain_phase2()
